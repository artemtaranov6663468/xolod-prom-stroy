let lang = localStorage.getItem("xps-lang") || "ru";
if (!I18N[lang]) lang = "ru";
let city = "all";

const dict = () => I18N[lang];

function applyText() {
  const d = dict();
  document.documentElement.lang = lang === "uz" ? "uz" : lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (d[key]) el.textContent = d[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = d[el.getAttribute("data-i18n-placeholder")] || "";
  });
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.classList.toggle("on", btn.getAttribute("data-set-lang") === lang);
  });
  const facts = document.getElementById("factsGrid");
  facts.innerHTML = d.facts.map(([k, v]) => `<article class="fact"><small>${k}</small><b>${v}</b></article>`).join("");
  const chips = document.getElementById("chips");
  chips.innerHTML = Object.entries(d.cities).map(([id, label]) =>
    `<button type="button" class="chip${id === city ? " on" : ""}" data-city="${id}">${label}</button>`
  ).join("");
  render();
}

function render() {
  const d = dict();
  const q = (document.getElementById("q").value || "").trim().toLowerCase();
  const items = PROJECTS.filter((p) => (city === "all" || p.city === city)).filter((p) => {
    if (!q) return true;
    const blob = [p.title[lang], p.place[lang], ...p.works[lang]].join(" ").toLowerCase();
    return blob.includes(q);
  });
  const grid = document.getElementById("grid");
  grid.innerHTML = items.map((p) => {
    const shot = p.img
      ? `<div class="shot"><img src="${p.img}" alt=""><i>${p.kind === "city" ? d.photoCity : d.photoPlace}</i></div>`
      : `<div class="shot"><i>${p.place[lang]}</i></div>`;
    const tags = p.works[lang].map((w) => `<span>${w}</span>`).join("");
    return `<article class="project">${shot}<div class="body"><div class="place">${p.place[lang]}</div><h3>${p.title[lang]}</h3><div class="works">${tags}</div></div></article>`;
  }).join("");
  document.getElementById("empty").style.display = items.length ? "none" : "block";
}

function requisitesText() {
  return dict().facts.map(([k, v]) => `${k}: ${v}`).join("\n");
}

document.getElementById("chips").addEventListener("click", (e) => {
  const btn = e.target.closest("[data-city]");
  if (!btn) return;
  city = btn.getAttribute("data-city");
  applyText();
});
document.getElementById("q").addEventListener("input", render);
document.querySelectorAll("[data-set-lang]").forEach((btn) => {
  btn.addEventListener("click", () => {
    lang = btn.getAttribute("data-set-lang");
    localStorage.setItem("xps-lang", lang);
    applyText();
  });
});
document.getElementById("copy").addEventListener("click", async () => {
  const btn = document.getElementById("copy");
  try {
    await navigator.clipboard.writeText(requisitesText());
  } catch (err) {
    const area = document.createElement("textarea");
    area.value = requisitesText();
    document.body.appendChild(area);
    area.select();
    document.execCommand("copy");
    area.remove();
  }
  const prev = dict().copy;
  btn.textContent = dict().copied;
  setTimeout(() => { btn.textContent = prev; }, 1600);
});

applyText();
