const CITIES = ["all", "tashkent", "bukhara", "khiva", "termez", "namangan", "beruniy", "other"];
let lang = localStorage.getItem("xps-lang") || "ru";
let city = "all";

function text(key) {
  return (I18N[lang] && I18N[lang][key]) || I18N.ru[key] || "";
}

function esc(value) {
  return String(value).replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[ch]));
}

function applyStatic() {
  document.documentElement.lang = lang === "uz" ? "uz" : lang;
  const titleKey = document.body.dataset.title || "titleHome";
  document.title = text(titleKey);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = text(el.dataset.i18n);
    if (value) el.textContent = value;
  });
  const search = document.getElementById("q");
  if (search) search.placeholder = text("searchPh");
  document.querySelectorAll(".langs button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
  const page = document.body.dataset.page;
  document.querySelectorAll(".nav a").forEach((a) => {
    if (a.dataset.nav === page) a.setAttribute("aria-current", "page");
    else a.removeAttribute("aria-current");
  });
}

function renderFilters() {
  const box = document.getElementById("filters");
  if (!box) return;
  box.innerHTML = CITIES.map((id) => {
    const count = id === "all" ? PROJECTS.length : PROJECTS.filter((p) => p.city === id).length;
    return `<button type="button" data-city="${id}" aria-pressed="${city === id}">${esc(text(id))} · ${count}</button>`;
  }).join("");
}

function renderProjects() {
  const root = document.getElementById("projects");
  const search = document.getElementById("q");
  if (!root || !search) return;
  const q = search.value.trim().toLowerCase();
  const list = PROJECTS.filter((p) => {
    if (city !== "all" && p.city !== city) return false;
    if (!q) return true;
    const bag = [p.title.ru, p.title.uz, p.title.en, p.place.ru, p.place.uz, p.place.en, p.work.ru, p.work.uz, p.work.en].join(" ").toLowerCase();
    return bag.includes(q);
  });
  if (!list.length) {
    root.innerHTML = `<div class="empty">${esc(text("empty"))}</div>`;
    return;
  }
  root.innerHTML = list.map((p) => {
    const photo = p.img
      ? `<div class="photo" style="background-image:url('${p.img}')"><span>${esc(p.place[lang])}</span></div>`
      : `<div class="photo plain"><span>${esc(p.place[lang])}</span></div>`;
    const note = p.credit
      ? `<div class="credit">${esc(p.credit[lang])}</div>`
      : p.img
        ? `<div class="credit">${esc(text("photoNote"))}</div>`
        : `<div class="credit">${esc(text("noPhoto"))}</div>`;
    const href = "https://yandex.uz/maps/?text=" + encodeURIComponent(p.map);
    return `<article class="project">${photo}<div class="body"><div class="where">${esc(p.place[lang])}</div><h3>${esc(p.title[lang])}</h3><p>${esc(p.work[lang])}</p><a class="maplink" href="${href}" target="_blank" rel="noopener">${esc(text("onMap"))}</a>${note}</div></article>`;
  }).join("");
}

